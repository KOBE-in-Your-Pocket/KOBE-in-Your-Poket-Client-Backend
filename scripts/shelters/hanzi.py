# 固有名詞に混ざる仮名の助詞。中国語では「之」を当てるのが通例
# （竹の台 → 竹之台 / 桜が丘 → 樱之丘）。
KANA_PARTICLES = {"の": "之", "ノ": "之", "が": "之", "ヶ": "之", "ケ": "之"}


def to_simplified(text: str) -> str:
    """字形が違う字を置き換え、仮名の助詞を「之」に当てる。対応が無い字はそのまま残す。"""
    return "".join(KANA_PARTICLES.get(char) or TO_SIMPLIFIED.get(char, char) for char in text)


